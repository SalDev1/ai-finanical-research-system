from app.llm.llm_client import LLMClient
from app.schemas.research import ResearchTaskPlan
from app.tools.research_validator import ResearchPlanValidator
from app.tools.json_extractor import extract_json
import json

# ResearchPlanner is dependent on LLMClient
class ResearchPlanner:
    def __init__(self, llm_client : LLMClient):
        self.llm_client = llm_client
        self.validator = ResearchPlanValidator()
        
    async def create_plan(self, question : str) -> ResearchTaskPlan:
        # We get the generated LLM research plan from the QWEN model. 
        response = await self.llm_client.generate_research_plan(question);
        # Validating the research plan generated by LLM model based on Pydantic Schema
        json_response = extract_json(response.get('response'))
        print(f"JSON Response from the LLM model : {json_response}")
        json_data = json.loads(json_response)
        research_plan_data = json_data['research_plan']
        plan = ResearchTaskPlan.model_validate(research_plan_data)
        print(f"Response generated from the LLM model : {plan}")
        plan = self.validator.validate(plan)
        return plan